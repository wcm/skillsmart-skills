#!/usr/bin/env python3
"""Scaffold a Glass Hero project, or add another glass page to one, starting from the closest example.

    python3 new_project.py <project-dir> <id> --from <example> --name "Halden" [--brand "Halden"] [--examples]

<example> is one of: urchin (prism rods bursting from a core, on black), cubes (a wall of glass blocks on a pale page),
twist (a ribbed glass knot in a dark room of coloured glows), flower (glass petals through a soft lens), or the two
light-only extras: halo (a long-exposure ring over a rainbow arch), plume (rainbow-fringed smoke).

First call creates the project:
    <project>/site/              index.html (brand filled in), main.js, base.css, engine/ (the glass, the stage)
    <project>/site/themes/       pages.json (dock order) + index.js (generated from it)
    <project>/.gitignore
Every call adds one page, copied from the example so it runs straight away:
    site/themes/<id>.js, <id>.css       the example's page with its id, number and name changed
--examples also adds the four main example pages after yours (for a demo or a series).
Nothing is generated and no network is called; serve site/ to see it.
"""
import argparse, json, re, shutil, sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
TEMPLATE = SKILL / "assets" / "template" / "site"
EXAMPLES = SKILL / "assets" / "examples"
MAIN = ["urchin", "cubes", "twist", "flower"]
EXTRAS = ["halo", "plume"]

ap = argparse.ArgumentParser()
ap.add_argument("project")
ap.add_argument("id", help="lowercase id for the page, e.g. 'halden' or 'night-glass'")
ap.add_argument("--from", dest="src", required=True, choices=MAIN + EXTRAS, help="the example to start from")
ap.add_argument("--name", required=True, help="the page's name (dock and default tab title), e.g. 'Halden'")
ap.add_argument("--brand", default="Glass Hero", help="the site's name in the tab title (first call only)")
ap.add_argument("--examples", action="store_true", help="also add the four main example pages (first call only)")
a = ap.parse_args()

if not re.fullmatch(r"[a-z][a-z0-9-]*", a.id):
    sys.exit("id must start with a letter and use lowercase letters, digits and dashes, e.g. 'halden' or 'night-glass'")
proj = Path(a.project).expanduser().resolve()
site, themes = proj / "site", proj / "site" / "themes"
manifest = themes / "pages.json"


def register(pages):
    """pages.json → index.js: one lazy import per page, in dock order."""
    manifest.write_text(json.dumps(pages, indent=2, ensure_ascii=False) + "\n")
    rows = [f"  {{ id: {json.dumps(p['id'])}, no: {json.dumps(p['no'])}, name: {json.dumps(p['name'], ensure_ascii=False)}, "
            f"bg: {json.dumps(p['bg'])}, load: () => import('./{p['id']}.js') }},"
            for p in pages]
    (themes / "index.js").write_text("// Generated by new_project.py from pages.json: the pages, in dock order.\nexport const PAGES = [\n"
                                     + "\n".join(rows) + "\n];\n")


def add_page(pid, src, name, pages):
    if any(p["id"] == pid for p in pages):
        sys.exit(f"{pid} is already a page in {proj}; pick another id")
    no = f"{len(pages) + 1:02d}"
    js = (EXAMPLES / f"{src}.js").read_text()
    js, n = re.subn(r'  id: "[^"]+", no: "[^"]+", name: "[^"]+"', f'  id: "{pid}", no: "{no}", name: {json.dumps(name, ensure_ascii=False)}', js, count=1)
    if not n:
        sys.exit(f"couldn't find the meta line in {src}.js")
    (themes / f"{pid}.js").write_text(js)
    (themes / f"{pid}.css").write_text((EXAMPLES / f"{src}.css").read_text().replace(f'data-theme="{src}"', f'data-theme="{pid}"'))
    bg = re.search(r'bg: "([^"]+)"', js).group(1)
    pages.append({"id": pid, "no": no, "name": name, "bg": bg, "from": src})
    return no


first = not (site / "main.js").exists()
if first:
    if proj.exists() and any(proj.iterdir()):
        sys.exit(f"{proj} exists, is not empty and is not a Glass Hero project; pick a new folder")
    shutil.copytree(TEMPLATE, site, ignore=shutil.ignore_patterns(".DS_Store"))
    themes.mkdir(exist_ok=True)  # empty folders don't survive the skill's ZIP, so make them here
    (site / "index.html").write_text((TEMPLATE / "index.html").read_text().replace("{{BRAND}}", a.brand))
    (proj / ".gitignore").write_text(".DS_Store\n")
    manifest.write_text("[]\n")
elif a.examples:
    sys.exit("--examples only works when creating a project")

pages = json.loads(manifest.read_text())
no = add_page(a.id, a.src, a.name, pages)
if a.examples:
    for ex in MAIN:
        if ex != a.id:
            add_page(ex, ex, re.search(r'name: "([^"]+)"', (EXAMPLES / f"{ex}.js").read_text()).group(1), pages)
register(pages)

print(f"{'created' if first else 'updated'} {proj}")
print(f"  page {no} {a.name}: site/themes/{a.id}.js + {a.id}.css, from the {a.src} example")
print(f"  preview: python3 -m http.server 5191 -d {site}   then open /#{a.id}")
