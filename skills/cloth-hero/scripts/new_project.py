#!/usr/bin/env python3
"""Scaffold a Cloth Hero project, or add another cloth page to one, starting from the closest example.

    python3 new_project.py <project-dir> <id> --from <example> --name "Velvet" [--brand "Maison Velours"] [--examples]

<example> is one of: afterhours (a hanging sheet you pull: vinyl, satin, any printed sheet), noren (split panels you
walk through: linen, a shop curtain), moongate (a bead curtain: one bead per pixel), tide (a long banner streaming in
a current: silk under water, a flag in wind).

First call creates the project:
    <project>/site/              index.html (brand filled in), main.js, base.css, engine/ (the cloth physics), img/
    <project>/site/themes/       pages.json (dock order) + index.js (generated from it)
    <project>/tools/             images.mjs, gen.mjs, images.json (prompts), package.json
    <project>/.gitignore
Every call adds one page, copied from the example so it runs straight away:
    site/themes/<id>.js, <id>.css       the example's page with its id, number and name changed
    site/img/<id>-*.webp                the example's pictures, to replace with the user's
    tools/images.json                   gains the example's prompts under the new names, to rewrite
--examples also adds the four example pages after yours (for a demo or a series).
Nothing is generated and no network is called; serve site/ to see it.
"""
import argparse, json, re, shutil, sys
from pathlib import Path

SKILL = Path(__file__).resolve().parent.parent
TEMPLATE = SKILL / "assets" / "template" / "site"
EXAMPLES = SKILL / "assets" / "examples"
TOOLS = SKILL / "assets" / "tools"
EXAMPLE_IDS = ["afterhours", "noren", "moongate", "tide"]
DOT = {"afterhours": "#ff2e88", "noren": "#1c2a4f", "moongate": "#c9a45c", "tide": "#0f6e8c"}

ap = argparse.ArgumentParser()
ap.add_argument("project")
ap.add_argument("id", help="lowercase id for the page, e.g. 'velvet' or 'night-swim'")
ap.add_argument("--from", dest="src", required=True, choices=EXAMPLE_IDS, help="the example to start from")
ap.add_argument("--name", required=True, help="the page's name (veil, dock and tab title), e.g. 'Velvet'")
ap.add_argument("--brand", default="Cloth Hero", help="the site's name in the tab title (first call only)")
ap.add_argument("--examples", action="store_true", help="also add the four example pages (first call only)")
a = ap.parse_args()

if not re.fullmatch(r"[a-z][a-z0-9-]*", a.id):
    sys.exit("id must start with a letter and use lowercase letters, digits and dashes, e.g. 'velvet' or 'night-swim'")
proj = Path(a.project).expanduser().resolve()
site, themes, tools = proj / "site", proj / "site" / "themes", proj / "tools"
manifest = themes / "pages.json"
examples_json = json.loads((EXAMPLES / "images.json").read_text())


def register(pages):
    """pages.json → index.js: one lazy import per page, in dock order."""
    manifest.write_text(json.dumps(pages, indent=2, ensure_ascii=False) + "\n")
    rows = [f"  {{ id: {json.dumps(p['id'])}, no: {json.dumps(p['no'])}, name: {json.dumps(p['name'], ensure_ascii=False)}, "
            f"dot: {json.dumps(p['dot'])}, load: () => import('./{p['id']}.js') }},"
            for p in pages]
    (themes / "index.js").write_text("// Generated by new_project.py from pages.json: the pages, in dock order.\nexport const PAGES = [\n"
                                     + "\n".join(rows) + "\n];\n")


def add_page(pid, src, name, pages):
    if any(p["id"] == pid for p in pages):
        sys.exit(f"{pid} is already a page in {proj}; pick another id")
    no = f"{len(pages) + 1:02d}"
    js = (EXAMPLES / f"{src}.js").read_text()
    js = js.replace(f"img/{src}-", f"img/{pid}-")
    js, n = re.subn(r'export const meta = \{ id: "[^"]+", no: "[^"]+", name: "[^"]+"',
                    f'export const meta = {{ id: "{pid}", no: "{no}", name: {json.dumps(name, ensure_ascii=False)}', js, count=1)
    if not n:
        sys.exit(f"couldn't find the meta line in {src}.js")
    (themes / f"{pid}.js").write_text(js)
    css = (EXAMPLES / f"{src}.css").read_text().replace(f'data-theme="{src}"', f'data-theme="{pid}"').replace(f"../img/{src}-", f"../img/{pid}-")
    (themes / f"{pid}.css").write_text(css)
    for img in sorted((EXAMPLES / "img").glob(f"{src}-*.webp")):
        shutil.copy2(img, site / "img" / img.name.replace(f"{src}-", f"{pid}-", 1))
    spec_path = tools / "images.json"
    spec = json.loads(spec_path.read_text())
    for key, entry in examples_json["images"].items():
        if entry["page"] == src:
            spec["images"][key.replace(f"{src}-", f"{pid}-", 1)] = {**entry, "page": pid}
    spec_path.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n")
    pages.append({"id": pid, "no": no, "name": name, "dot": DOT[src], "from": src})
    return no


# ——— create the project on first use ———
first = not (site / "main.js").exists()
if first:
    if proj.exists() and any(proj.iterdir()):
        sys.exit(f"{proj} exists, is not empty and is not a Cloth Hero project; pick a new folder")
    shutil.copytree(TEMPLATE, site, ignore=shutil.ignore_patterns(".DS_Store"))
    themes.mkdir(exist_ok=True)  # empty folders don't survive the skill's ZIP, so make them here
    (site / "img").mkdir(exist_ok=True)
    (site / "index.html").write_text((TEMPLATE / "index.html").read_text().replace("{{BRAND}}", a.brand))
    tools.mkdir(parents=True)
    for f in ("gen.mjs", "images.mjs", "package.json"):
        shutil.copy2(TOOLS / f, tools / f)
    (tools / "images.json").write_text(json.dumps({"photo": examples_json["photo"], "flat": examples_json["flat"], "images": {}},
                                                  indent=2, ensure_ascii=False) + "\n")
    (proj / ".gitignore").write_text(".DS_Store\nnode_modules/\ntools/out/\n")
    manifest.write_text("[]\n")
elif a.examples:
    sys.exit("--examples only works when creating a project")

pages = json.loads(manifest.read_text())
no = add_page(a.id, a.src, a.name, pages)
if a.examples:
    for ex in EXAMPLE_IDS:
        if ex != a.id:
            meta = re.search(r'name: "([^"]+)"', (EXAMPLES / f"{ex}.js").read_text()).group(1)
            add_page(ex, ex, meta, pages)
register(pages)

print(f"{'created' if first else 'updated'} {proj}")
print(f"  page {no} {a.name}: site/themes/{a.id}.js + {a.id}.css, from the {a.src} example (its pictures are placeholders)")
print(f"  prompts: tools/images.json ({', '.join(k for k in json.loads((tools / 'images.json').read_text())['images'] if k.startswith(a.id + '-'))})")
print(f"  preview: python3 -m http.server 5190 -d {site}   then open /#{a.id}")
